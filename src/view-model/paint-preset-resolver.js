import {
  BAR_PAINT_DIAGNOSTICS, INVALID_PAINT_OPACITY, PAINT_PROPERTY_SOURCES, normalizeBarConfig, normalizePaintOpacity,
} from '../config/normalize.js';

const PRESET_PROPERTIES = new Set(['fill_style', 'color', 'solid_fill', 'segments', 'gradient_stops']);
const PRESET_PATH = 'paint.preset';
const THEME_ACCENT_FALLBACK = 'var(--accent-color, #4a9eff)';

function isRecord(value) {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) return false;
  const prototype = Object.getPrototypeOf(value);
  return prototype === Object.prototype || prototype === null;
}

function cloneValue(value) {
  if (Array.isArray(value)) return value.map(cloneValue);
  if (!isRecord(value)) return value;
  const clone = {};
  for (const key of Object.keys(value)) {
    Object.defineProperty(clone, key, { value: cloneValue(value[key]), enumerable: true, writable: true, configurable: true });
  }
  return clone;
}

function normalizeDefinition(definition, { preset = false, canonical = false } = {}) {
  if (!isRecord(definition)) return { paint: null, issue: { property: null, reason: 'definition_must_be_object' } };
  if (preset) {
    const unsupported = Object.keys(definition).find(property => !PRESET_PROPERTIES.has(property));
    if (unsupported) return { paint: null, issue: { property: unsupported, reason: 'unsupported_preset_property' } };
  }

  const input = cloneValue(definition);
  if (canonical) {
    // Normalized paints include null inactive collections; omit them when
    // passing back through the raw-config normalizer.
    if (input.segments === null) delete input.segments;
    if (input.gradient_stops === null) delete input.gradient_stops;
  }
  const normalized = normalizeBarConfig({ bar: { paint: input } }, null, { isCardScope: true });
  const issues = normalized[BAR_PAINT_DIAGNOSTICS] ?? [];
  if (issues.length) {
    return { paint: null, issue: {
      property: issues[0].property ?? null,
      reason: 'invalid_paint_property',
    } };
  }
  return { paint: normalized.paint, issue: null };
}

function inheritedOpacity(inheritedPaint) {
  return normalizePaintOpacity({ opacity: inheritedPaint?.opacity }).opacity;
}

function defaultPaint(themeAccent) {
  const color = typeof themeAccent === 'string' && themeAccent.trim()
    ? themeAccent
    : THEME_ACCENT_FALLBACK;
  return normalizeDefinition({ fill_style: 'bands', color, solid_fill: false }).paint;
}

function getPresetMap(registry) {
  return isRecord(registry?.presets) ? registry.presets : null;
}

function localOverrides(localPaint) {
  const overrides = cloneValue(localPaint);
  delete overrides.preset;
  return overrides;
}

function mergeBase(base, overrides, opacity) {
  const result = { ...base, ...overrides, opacity };
  delete result.preset;
  // These compatibility mirrors are generated by normalizeBarConfig and are
  // recalculated from the effective fill properties below.
  delete result.color_mode;
  delete result.severity;
  return result;
}

function makeDiagnostic(code, reference, fallback, reason = null) {
  return {
    code,
    severity: 'warning',
    path: PRESET_PATH,
    reference,
    fallback,
    ...(reason ? { reason } : {}),
  };
}

function registryIsLoading(registry) {
  return registry == null || registry.status === 'loading';
}

function registryIsUnavailable(registry) {
  return registry?.status === 'error'
    || ['connection_unavailable', 'dashboard_unavailable', 'dashboard_config_unavailable']
      .includes(registry?.diagnostic?.code);
}

/** Resolve a local canonical paint against a supplied dashboard registry. */
export function resolvePaintPreset({ paint, registry, inheritedPaint = null, themeAccent } = {}) {
  const inherited = normalizeDefinition(inheritedPaint, { canonical: true });
  const fallbackPaint = inherited.paint ?? defaultPaint(themeAccent);
  const diagnostics = [];
  const localIsRecord = isRecord(paint);
  const local = localIsRecord ? localOverrides(paint) : {};
  const hasReference = localIsRecord && Object.prototype.hasOwnProperty.call(paint, 'preset');
  const reference = hasReference ? paint.preset : null;
  const hasValidReference = typeof reference === 'string' && reference.trim() !== '';

  if (paint !== undefined && !localIsRecord) {
    diagnostics.push(makeDiagnostic('paint_definition_invalid', null, inherited.paint ? 'inherited' : 'default', 'definition_must_be_object'));
  }

  let base = fallbackPaint;
  let source = inherited.paint ? 'inherited' : 'default';
  if (hasReference) {
    if (!hasValidReference) {
      diagnostics.push(makeDiagnostic('paint_preset_reference_invalid', reference, inherited.paint ? 'inherited' : 'default', 'reference_must_be_nonempty_string'));
    } else if (registryIsLoading(registry)) {
      // Do not report a missing name until the dashboard read has completed.
    } else {
      const presets = getPresetMap(registry);
      if (registryIsUnavailable(registry)) {
        diagnostics.push(makeDiagnostic('paint_registry_unavailable', reference,
          inherited.paint ? 'inherited' : 'default', registry?.diagnostic?.code ?? 'registry_unavailable'));
      } else if (!presets || !Object.prototype.hasOwnProperty.call(presets, reference)) {
        diagnostics.push(makeDiagnostic('paint_preset_missing', reference, inherited.paint ? 'inherited' : 'default'));
      } else {
        const normalizedPreset = normalizeDefinition(presets[reference], { preset: true });
        if (normalizedPreset.issue) {
          diagnostics.push(makeDiagnostic('paint_preset_invalid', reference, inherited.paint ? 'inherited' : 'default',
            normalizedPreset.issue.reason));
        } else {
          base = normalizedPreset.paint;
          source = 'preset';
        }
      }
    }
  }

  let validLocalOverrides = true;
  if (Object.keys(local).length) {
    const checkedLocal = normalizeDefinition(local);
    if (checkedLocal.issue) {
      validLocalOverrides = false;
      diagnostics.push(makeDiagnostic('paint_definition_invalid', reference, inherited.paint ? 'inherited' : 'default',
        checkedLocal.issue.reason));
      base = fallbackPaint;
      source = inherited.paint ? 'inherited' : 'default';
    }
  }

  const overrides = validLocalOverrides ? local : Object.fromEntries(
    Object.prototype.hasOwnProperty.call(local, 'opacity') ? [['opacity', local.opacity]] : [],
  );
  const opacity = Object.prototype.hasOwnProperty.call(local, 'opacity') && local.opacity !== undefined
    ? local.opacity
    : inheritedOpacity(inheritedPaint);
  const effective = normalizeDefinition(mergeBase(base, overrides, opacity), { canonical: true });
  const resultPaint = effective.paint ?? defaultPaint(themeAccent);

  if (!inherited.paint && inheritedPaint != null) {
    diagnostics.push(makeDiagnostic('inherited_paint_invalid', reference, 'default',
      inherited.issue?.reason ?? 'invalid_paint_definition'));
  }
  if (Object.prototype.hasOwnProperty.call(resultPaint, INVALID_PAINT_OPACITY)) {
    diagnostics.push({
      code: 'paint_opacity_invalid', severity: 'warning', path: 'paint.opacity',
      reference: hasValidReference ? reference : null, fallback: 'default_opacity',
    });
  }

  return {
    paint: resultPaint,
    diagnostics,
    source,
  };
}

/** Resolve normalized card and entity paint layers using their authored-source metadata. */
export function authoredPaintProperties(normalizedPaint) {
  return Object.fromEntries(
    Object.keys(normalizedPaint?.[PAINT_PROPERTY_SOURCES] ?? {})
      .filter(property => Object.prototype.hasOwnProperty.call(normalizedPaint, property))
      .map(property => [property, normalizedPaint[property]]),
  );
}

export function resolveScopedPaintPreset({ inheritedPaint, paint, registry, themeAccent } = {}) {
  const inheritedProperties = authoredPaintProperties(inheritedPaint);
  const inheritedFallback = { ...inheritedPaint };
  delete inheritedFallback.preset;
  const inherited = resolvePaintPreset({
    paint: inheritedProperties, registry, inheritedPaint: inheritedFallback, themeAccent,
  });
  const local = resolvePaintPreset({
    paint: authoredPaintProperties(paint), registry, inheritedPaint: inherited.paint, themeAccent,
  });
  return {
    paint: local.paint,
    diagnostics: [...inherited.diagnostics, ...local.diagnostics],
    source: local.source,
  };
}
